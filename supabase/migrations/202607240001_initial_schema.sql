create or replace function public.bootstrap_workspace()
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_team_id uuid;
  new_team_id uuid;
  aura_project_id uuid;
  brava_project_id uuid;
  nexo_project_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  insert into public.profiles (id, full_name)
  values (auth.uid(), 'Dirección de cuentas')
  on conflict (id) do nothing;

  select team_id into existing_team_id
  from public.team_members
  where user_id = auth.uid()
  order by joined_at
  limit 1;

  if existing_team_id is not null then
    return existing_team_id;
  end if;

  insert into public.teams (name, slug, created_by)
  values (
    'Prisma Agencia',
    'prisma-agency-' || substr(replace(auth.uid()::text, '-', ''), 1, 8),
    auth.uid()
  )
  returning id into new_team_id;

  insert into public.team_members (team_id, user_id, role)
  values (new_team_id, auth.uid(), 'owner');

  insert into public.projects (team_id, name, slug, color)
  values (new_team_id, 'Lanzamiento Aura', 'lanzamiento-aura', '#6556EE')
  returning id into aura_project_id;

  insert into public.projects (team_id, name, slug, color)
  values (new_team_id, 'Verano Brava', 'verano-brava', '#EF6A67')
  returning id into brava_project_id;

  insert into public.projects (team_id, name, slug, color)
  values (new_team_id, 'Always-on Nexo', 'always-on-nexo', '#3C8FD5')
  returning id into nexo_project_id;

  insert into public.tasks (
    team_id, project_id, title, description, status, priority,
    assignee_id, client_name, due_date, tags
  )
  values
    (
      new_team_id, aura_project_id, 'Adaptar campaña de lanzamiento a stories',
      'Preparar seis piezas verticales a partir del key visual aprobado.',
      'en_progreso', 'urgente', auth.uid(), 'Aura Cosmética',
      current_date, array['Social', 'Stories']
    ),
    (
      new_team_id, brava_project_id, 'Cerrar copies para campaña de invierno',
      'Redactar concepto, copy principal y variantes para Meta Ads.',
      'nuevo', 'alta', auth.uid(), 'Brava Bebidas',
      current_date + 1, array['Copy', 'Campaña']
    ),
    (
      new_team_id, nexo_project_id, 'Configurar pauta de Meta para agosto',
      'Preparar campañas, audiencias y distribución de presupuesto.',
      'nuevo', 'media', null, 'Nexo Educación',
      current_date + 1, array['Paid Media', 'Meta']
    );

  return new_team_id;
end;
$$;

revoke all on function public.bootstrap_workspace() from public;
grant execute on function public.bootstrap_workspace() to authenticated;

create or replace function public.create_workspace(workspace_name text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_team_id uuid;
  normalized_name text := trim(workspace_name);
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if char_length(normalized_name) < 2 or char_length(normalized_name) > 80 then
    raise exception 'Workspace name must contain between 2 and 80 characters';
  end if;

  insert into public.profiles (id, full_name)
  values (auth.uid(), 'Integrante')
  on conflict (id) do nothing;

  insert into public.teams (name, slug, created_by)
  values (
    normalized_name,
    'workspace-'
      || substr(replace(auth.uid()::text, '-', ''), 1, 8)
      || '-'
      || floor(extract(epoch from clock_timestamp()) * 1000)::bigint,
    auth.uid()
  )
  returning id into new_team_id;

  insert into public.team_members (team_id, user_id, role)
  values (new_team_id, auth.uid(), 'owner');

  return new_team_id;
end;
$$;

revoke all on function public.create_workspace(text) from public;
grant execute on function public.create_workspace(text) to authenticated;
